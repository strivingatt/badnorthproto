using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Копейщик (Spearman) — ближний бой увеличенной дистанции: основная форма удара
/// — копьё, которое достаёт клетку на расстоянии 2 прямо по Facing (через одну
/// клетку). За счёт этого фронт может стоять во втором ряду строя и доставать
/// врага через своего же юнита (свои не получают урон — фильтр по команде в
/// TryAttack унаследован от Militia). Плюс страховка от «мёртвой зоны»: смежные
/// 3 клетки бьются как у базового Militia, чтобы копейщик не был беспомощен,
/// когда враг подошёл вплотную (баг P0 — два копейщика смотрели друг на друга).
///
/// Статы: крепче ополченца (6 HP), сильнее бьёт (2), но медленнее перезарядка
/// (1.2 с). PreferredAttackRange = 2 — ИИ встаёт в двух клетках от цели
/// (там, где копьё достаёт), вплотную не лезет.
/// </summary>
public class Spearman : Militia
{
    private void Awake()
    {
        maxHp = 6;
        attackDamage = 2;
        attackCooldown = 1.2f;
    }

    /// <summary>Дистанция боя для ИИ: 2 клетки (бьём через одну).</summary>
    public override int PreferredAttackRange => 2;

    /// <summary>
    /// Зона атаки копейщика = КОПЬЁ (три клетки на дистанции 2: прямо по facing
    /// и ±45°, та же таблица Rot45, что у ближнего боя, но с шагом 2) ПЛЮС
    /// ближний бой базового Militia (три смежные клетки).
    ///
    /// Копьё — основная форма удара: второй ряд строя достаёт врага через своего
    /// (осевые направления дают (±2,0)/(0,±2), диагональные — (±2,±2)).
    /// Смежные клетки добавлены как страховка от «мёртвой зоны» (баг P0): раньше
    /// копейщик бил ТОЛЬКО на дистанции 2, поэтому два копейщика (или копейщик и
    /// враг, подошедший вплотную) стояли и смотрели друг на друга, не нанося
    /// урона вовсе.
    /// </summary>
    public override List<Vector2Int> GetAttackCells(Vector2Int origin, Vector2Int facing)
    {
        List<Vector2Int> cells = base.GetAttackCells(origin, facing);

        if (Rot45.TryGetValue(facing, out var pair))
        {
            cells.Add(origin + facing * 2);      // центр копья (через клетку)
            cells.Add(origin + pair.cw45 * 2);   // луч копья по часовой
            cells.Add(origin + pair.ccw45 * 2);  // луч копья против часовой
        }
        else
        {
            // facing вне таблицы 8 направлений (защита): колем хотя бы прямо.
            cells.Add(origin + facing * 2);
        }

        return cells;
    }
}
